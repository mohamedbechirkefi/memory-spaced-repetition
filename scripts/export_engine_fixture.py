"""Small engine fixture for the demo's browser port (M5).

Runs the committed Python engine on four small cases (one simulated learner
each, at most a few milliseconds of compute) and writes the common random
numbers together with every arm's trace to
``demo/src/fixtures/engine_fixture.json``. The vitest suite feeds the same
random numbers to the TypeScript port and compares the traces. Exploratory
by construction: these are engine-check runs, not results.

Usage: ``.venv/bin/python scripts/export_engine_fixture.py [--check]``
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from memory_research.config import SimConfig
from memory_research.environment import repo_root
from memory_research.items import draw_common_random_numbers
from memory_research.simulate import recall_at, simulate

ROOT = repo_root()
OUT = Path("demo/src/fixtures/engine_fixture.json")
ARMS5 = ["uniform", "expanding", "massed", "leitner", "greedy"]


def cases() -> list[dict[str, Any]]:
    base1 = json.loads((ROOT / "research/experiments/EXP-001/config.json").read_text())["base"]
    cfg2 = json.loads((ROOT / "research/experiments/EXP-002/config.json").read_text())
    return [
        {"id": "exp001-central", "config": base1, "arms": ARMS5, "seed": 1000},
        {"id": "exp002-central", "config": cfg2["base"], "arms": cfg2["arms"], "seed": 1000},
        {"id": "exp-k2-bimodal-ri7", "config": {**base1, "reviews_per_item": 2, "item_distribution": "bimodal",
                                                 "retention_interval_days": 7}, "arms": ARMS5, "seed": 7},
        {"id": "power-k8-homogeneous-ri1", "config": {**cfg2["base"], "reviews_per_item": 8,
                                                       "item_distribution": "homogeneous", "retention_interval_days": 1},
         "arms": ARMS5 + ["greedy-exp"], "seed": 11},
    ]


def build() -> dict[str, Any]:
    out = []
    for case in cases():
        cfg = SimConfig.from_dict(case["config"])
        crn = draw_common_random_numbers(cfg, case["seed"])
        arms = {}
        for arm in case["arms"]:
            tr = simulate(cfg, arm, crn)
            arms[arm] = {
                "event_session": tr.event_session.tolist(),
                "event_item": tr.event_item.tolist(),
                "event_success": [int(x) for x in tr.event_success],
                "final_rate": tr.final_rate.tolist(),
                "last_review_day": tr.last_review_day.tolist(),
                "test_recall_prob": tr.test_recall_prob.tolist(),
                "recall_mean": float(tr.test_recall_prob.mean()),
                "recall_mean_at_ri30": float(recall_at(cfg, tr, 30).mean()),
            }
        out.append({
            "id": case["id"],
            "config": cfg.to_dict(),
            "seed": case["seed"],
            "crn": {
                "half_lives_days": crn.half_lives_days.tolist(),
                "review_uniforms": crn.review_uniforms.tolist(),
                "test_uniforms": crn.test_uniforms.tolist(),
            },
            "arms": arms,
        })
    return {
        "fixture": "memory-engine-fixture",
        "version": "1.0.0",
        "note": "Generated by scripts/export_engine_fixture.py from the committed Python engine. Engine check only, not a result.",
        "cases": out,
    }


def render(data: dict[str, Any]) -> str:
    return json.dumps(data, separators=(",", ":")) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(build())
    path = ROOT / OUT
    if args.check:
        same = path.is_file() and path.read_text() == text
        print("FIXTURE-CHECK " + ("PASS" if same else "FAIL"))
        return 0 if same else 1
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
