"""Copy the generated evidence of a confirmatory experiment into its record
folder `research/experiments/EXP-NNN/` and write `results_tables.md`.

Every number in results_tables.md is read from
`results/confirmatory/EXP-NNN/analysis/frozen_analysis.json`; none is typed.

  .venv/bin/python scripts/build_experiment_records.py EXP-001 EXP-002 EXP-003
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from memory_research.environment import repo_root


def f(x, nd=4):
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, float):
        return f"{x:.2e}" if (x != 0 and abs(x) < 1e-4) else f"{x:.{nd}f}"
    return str(x)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(out + ["| " + " | ".join(f(v) for v in r) + " |" for r in rows])


def contrast_rows(cs, holm_key="p_holm"):
    return [[c["arm"] + " - " + c["baseline"], c["n_pairs"], c["mean_diff"], c["relative_change"],
             f"[{f(c['boot_ci_low'])}, {f(c['boot_ci_high'])}]", f"[{f(c['t_ci_low'])}, {f(c['t_ci_high'])}]",
             c["sd_diff"], c["d_z"], c["p_value"], c.get(holm_key), c["verdict_rule"]] for c in cs]


CH = ["contrast", "pairs", "mean diff", "relative", "bootstrap 95% CI", "paired t 95% CI", "s", "d_z", "p", "p (Holm)", "section 4 rule"]


def arm_rows(rows):
    return [[r["arm"], r["recall_mean_n"], r["recall_mean_mean"], r.get("recall_mean_sd"),
             f"[{f(r['recall_mean_boot_ci_low'])}, {f(r['recall_mean_boot_ci_high'])}]", r["observed_recall_mean"],
             r["mastery_share_mean"], r["recall_min_mean"], r["recall_p10_mean"], r["calibration_mae_mean"],
             r["peak_daily_load_mean"], r["sessions_used_mean"]] for r in rows]


AH = ["arm", "n", "mean R", "SD", "bootstrap 95% CI", "observed recall", "mastery share", "min item recall", "p10 item recall",
      "calibration MAE", "peak daily load", "sessions used"]


def build(exp: str, root: Path) -> Path:
    src = root / "results" / "confirmatory" / exp
    a = json.loads((src / "analysis" / "frozen_analysis.json").read_text(encoding="utf-8"))
    dst = root / "research" / "experiments" / exp
    (dst / "figures").mkdir(parents=True, exist_ok=True)
    for p in sorted((src / "analysis" / "figures").glob("*")) + sorted((src / "report" / "figures").glob("*")):
        shutil.copy2(p, dst / "figures" / p.name)
    lines = ["<!-- SPDX-License-Identifier: LicenseRef-MEMORY-NC-Research-1.0 -->",
             f"# {exp} results tables (generated)", "",
             f"Generated by `scripts/build_experiment_records.py` from `results/confirmatory/{exp}/analysis/frozen_analysis.json` "
             f"(result file SHA-256 `{a['result_sha256']}`, analysis at `{a['analysis_generator']['git_revision']}`). "
             "No number is typed by hand. Units: probability (0 to 1). Intervals: 95% percentile bootstrap over seeds "
             "(10,000 resamples, seed 20261124) and paired t.", "",
             f"Runs: {a['counts']['n_runs']} planned and run, {a['counts']['n_ok']} ok, {a['counts']['n_excluded']} excluded, "
             f"{a['counts']['n_failed']} failed.", ""]
    if exp == "EXP-001":
        shutil.copy2(src / "analysis" / "contrasts.csv", dst / "metrics.csv")
        p = a["primary"]
        lines += ["## Primary contrast (greedy minus uniform)", "", table(CH[:-2] + ["verdict"], [contrast_rows([p])[0][:-2] + [p["verdict"]]]), "",
                  "## All contrasts versus uniform (Holm over the four)", "", table(CH, contrast_rows(a["secondary_contrasts_holm4"])), "",
                  "## Metric-choice sensitivity of the primary contrast (EXP-001 section 16)", "",
                  table(["metric", "mean diff", "bootstrap 95% CI", "paired t 95% CI", "same sign as primary"],
                        [[s["metric"], s["mean_diff"], f"[{f(s['boot_ci_low'])}, {f(s['boot_ci_high'])}]",
                          f"[{f(s['t_ci_low'])}, {f(s['t_ci_high'])}]", s["same_sign_as_primary"]] for s in a["sensitivity_metric_choice"]]), "",
                  f"Conclusion restricted to the mean (a sensitivity metric changes sign): {f(a['conclusion_restricted_to_mean'])}.", "",
                  "## Per-arm summary (means over 50 seeds)", "", table(AH, arm_rows(a["arm_summary"])), ""]
    elif exp == "EXP-002":
        shutil.copy2(src / "analysis" / "contrasts.csv", dst / "metrics.csv")
        r = a["interpretation_rule"]
        lines += ["## Primary contrasts (Holm over the two)", "", table(CH, contrast_rows(a["primary_contrasts_holm2"])), "",
                  "## Interpretation rule (EXP-002 section 4)", "",
                  table(["quantity", "value"], [[k, v] for k, v in r.items()]), "",
                  "## All contrasts versus uniform (descriptive; Holm over all five)", "", table(CH, contrast_rows(a["secondary_contrasts_holm_all"])), "",
                  "## Per-arm summary (means over 50 seeds)", "", table(AH, arm_rows(a["arm_summary"])), ""]
    else:
        shutil.copy2(src / "analysis" / "cells.csv", dst / "metrics.csv")
        e1, e2 = a["e1_massed_improves_as_ri_decreases"], a["e2_greedy_advantage_smallest_homogeneous"]
        cells = a["cells"]
        arms = [k[5:] for k in cells[0] if k.startswith("diff_")]
        lines += [f"**{a['label']}**", "",
                  "## Summary counts", "",
                  table(["quantity", "value"], [
                      ["cells", len(cells)], ["EXP-001 rank order (reference)", " > ".join(a["exp001_rank_order"])],
                      ["cells with at least one pairwise rank reversal vs EXP-001", a["cells_with_any_reversal_vs_exp001"]],
                      ["cells whose top arm differs from EXP-001 (greedy)", a["cells_with_top_arm_change_vs_exp001"]],
                      ["cells where greedy minus uniform has the opposite sign to EXP-001", a["cells_with_greedy_sign_change_vs_exp001"]],
                      ["E1 (massed minus uniform non-increasing in RI): groups where it holds", f"{e1['holds_in']} of {e1['of']}"],
                      ["E2 (greedy advantage smallest for homogeneous items): groups where it holds", f"{e2['holds_in']} of {e2['of']}"],
                  ] + [[f"cells where the {arm} - uniform interval lies entirely above 0 / below 0",
                        f"{sum(c[f'ci_{arm}'][0] > 0 for c in cells)} / {sum(c[f'ci_{arm}'][1] < 0 for c in cells)}"] for arm in arms]
                        + [["top arm by mean R: " + arm, sum(c["rank_order"][0] == arm for c in cells)] for arm in cells[0]["means"]]), "",
                  "## Per cell: mean R per arm, greedy minus uniform with interval, rank order", "",
                  table(["cell", "model", "k", "RI", "items"] + [f"R {x}" for x in cells[0]["means"]] + ["greedy - uniform", "bootstrap 95% CI", "rank order", "first-rank share greedy"],
                        [[c["cell_id"], c["true_model"], c["reviews_per_item"], c["retention_interval_days"], c["item_distribution"]]
                         + [c["means"][x] for x in c["means"]] + [c["diff_greedy"], f"[{f(c['ci_greedy'][0])}, {f(c['ci_greedy'][1])}]",
                                                                  " > ".join(c["rank_order"]), c["first_rank_share"]["greedy"]] for c in cells]), ""]
    out = dst / "results_tables.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


if __name__ == "__main__":
    root = repo_root()
    for exp in sys.argv[1:] or ["EXP-001", "EXP-002", "EXP-003"]:
        print(build(exp, root))
